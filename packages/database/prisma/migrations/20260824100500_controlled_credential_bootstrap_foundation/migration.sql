BEGIN;

-- ============================================================================
-- SUKUU STAGE 3B PHASE 2C
-- Controlled Credential Bootstrap Foundation
--
-- No fixed password is created by this migration.
--
-- A credential challenge:
--   - contains only a cryptographic HASH of the one-time token
--   - is single-use
--   - expires
--   - is revocable
--   - cannot be read directly by the application runtime
--
-- The plaintext activation token exists only at issuance time and must be
-- transferred to the authorised account holder out-of-band.
-- ============================================================================


-- --------------------------------------------------------------------------
-- 1. Preconditions.
-- --------------------------------------------------------------------------

DO $preflight$
BEGIN

  IF to_regclass(
    'system.system_user'
  ) IS NULL THEN
    RAISE EXCEPTION
      'Phase 2C aborted: system_user table missing';
  END IF;


  IF to_regclass(
    'system.system_password_history'
  ) IS NULL THEN
    RAISE EXCEPTION
      'Phase 2C aborted: password-history table missing';
  END IF;


  IF to_regclass(
    'system.system_session'
  ) IS NULL THEN
    RAISE EXCEPTION
      'Phase 2C aborted: session table missing';
  END IF;


  IF to_regprocedure(
    'system._auth_password_matches(text,text)'
  ) IS NULL THEN
    RAISE EXCEPTION
      'Phase 2C aborted: database password verifier missing';
  END IF;

END
$preflight$;


-- --------------------------------------------------------------------------
-- 2. One-time credential challenges.
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS
  system.system_credential_challenge
(
  id uuid
    PRIMARY KEY
    DEFAULT gen_random_uuid(),

  user_id text
    NOT NULL,

  school_id text
    NOT NULL,

  purpose text
    NOT NULL,

  token_hash text
    NOT NULL,

  issued_by text,

  created_at timestamptz
    NOT NULL
    DEFAULT CURRENT_TIMESTAMP,

  expires_at timestamptz
    NOT NULL,

  consumed_at timestamptz,

  revoked_at timestamptz,

  attempt_count integer
    NOT NULL
    DEFAULT 0,

  max_attempts integer
    NOT NULL
    DEFAULT 5,

  CONSTRAINT
    system_credential_challenge_purpose_check
  CHECK (
    purpose IN (
      'FIRST_CREDENTIAL',
      'PASSWORD_RESET',
      'COMPROMISED_ROTATION'
    )
  ),

  CONSTRAINT
    system_credential_challenge_attempt_check
  CHECK (
    attempt_count >= 0
    AND max_attempts BETWEEN 1 AND 20
  )
);


CREATE UNIQUE INDEX IF NOT EXISTS
  uq_system_credential_challenge_token_hash
ON
  system.system_credential_challenge
  (token_hash);


CREATE UNIQUE INDEX IF NOT EXISTS
  uq_system_credential_challenge_open_user
ON
  system.system_credential_challenge
  (user_id)
WHERE
  consumed_at IS NULL
  AND revoked_at IS NULL;


CREATE INDEX IF NOT EXISTS
  idx_system_credential_challenge_school
ON
  system.system_credential_challenge
  (school_id);


CREATE INDEX IF NOT EXISTS
  idx_system_credential_challenge_expiry
ON
  system.system_credential_challenge
  (expires_at);


ALTER TABLE
  system.system_credential_challenge
ENABLE ROW LEVEL SECURITY;


ALTER TABLE
  system.system_credential_challenge
FORCE ROW LEVEL SECURITY;


REVOKE ALL
ON TABLE
  system.system_credential_challenge
FROM PUBLIC;


DO $runtime_table_lock$
