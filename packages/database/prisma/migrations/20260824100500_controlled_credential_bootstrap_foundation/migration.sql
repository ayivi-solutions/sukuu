-- --------------------------------------------------------------------------
-- 7. Credential-vault postconditions.
-- --------------------------------------------------------------------------

DO $credential_vault_postcheck$
BEGIN

  IF to_regprocedure(
    'system.auth_change_own_password(text,text,text)'
  ) IS NULL THEN

    RAISE EXCEPTION
      'Phase 2C post-check failed: trusted password-change function missing';

  END IF;


  IF EXISTS (
    SELECT 1

    FROM pg_catalog.pg_policies

    WHERE
      schemaname='system'
      AND tablename='system_password_history'
      AND policyname='own_or_colleague'
  ) THEN

    RAISE EXCEPTION
      'Phase 2C post-check failed: legacy password-history policy remains';

  END IF;


  IF EXISTS (
    SELECT 1
    FROM pg_catalog.pg_roles
    WHERE rolname='sukuu_app_runtime'
  )
  AND (
    has_table_privilege(
      'sukuu_app_runtime',
      'system.system_password_history',
      'SELECT'
    )
    OR
    has_table_privilege(
      'sukuu_app_runtime',
      'system.system_password_history',
      'INSERT'
    )
    OR
    has_table_privilege(
      'sukuu_app_runtime',
      'system.system_password_history',
      'UPDATE'
    )
    OR
    has_table_privilege(
      'sukuu_app_runtime',
      'system.system_password_history',
      'DELETE'
    )
  ) THEN

    RAISE EXCEPTION
      'Phase 2C post-check failed: runtime retains direct password-history table access';

  END IF;

END
$credential_vault_postcheck$;


-- --------------------------------------------------------------------------
-- 8. Postconditions.
-- --------------------------------------------------------------------------

DO $postcheck$
BEGIN

  IF to_regclass(
    'system.system_credential_challenge'
  ) IS NULL THEN

    RAISE EXCEPTION
      'Phase 2C post-check failed: challenge table missing';

  END IF;


  IF to_regprocedure(
    'system.auth_redeem_credential_challenge(text,text,text)'
  ) IS NULL THEN

    RAISE EXCEPTION
      'Phase 2C post-check failed: redemption function missing';

  END IF;

END
$postcheck$;


COMMIT;
