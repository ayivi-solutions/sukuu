  END IF;

END
$runtime_table_lock$;


-- --------------------------------------------------------------------------
-- 3. Raise current tenant password-policy floor.
--
-- We do not alter the existing expiry interval here.
-- --------------------------------------------------------------------------

UPDATE
  system.system_password_policy

SET
  min_length =
    GREATEST(min_length,12),

  require_uppercase = true,
  require_lowercase = true,
  require_numbers = true,
  require_symbols = true;


-- --------------------------------------------------------------------------
-- 4. Redeem one credential challenge.
--
-- p_new_password is used only for password-history comparison and is NEVER
-- persisted.
--
-- p_new_password_hash is the bcrypt hash generated by the API.
-- --------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION
  system.auth_redeem_credential_challenge(
    p_token_hash text,
    p_new_password text,
    p_new_password_hash text
  )
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path =
  pg_catalog,
  system,
  sukuux
AS $function$

DECLARE

  v_challenge
    system.system_credential_challenge%ROWTYPE;

  v_user
    system.system_user%ROWTYPE;

BEGIN

  IF
    p_token_hash IS NULL
    OR length(p_token_hash) <> 64
    OR p_new_password IS NULL
    OR p_new_password_hash IS NULL
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID'
    );

  END IF;


  -- Defence in depth.
  -- The API performs the same rules before bcrypt hashing.

  IF
    length(p_new_password) < 12
    OR p_new_password !~ '[A-Z]'
    OR p_new_password !~ '[a-z]'
    OR p_new_password !~ '[0-9]'
    OR p_new_password !~ '[^A-Za-z0-9]'
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'WEAK_PASSWORD'
    );

  END IF;


  SELECT
    c.*

  INTO
    v_challenge

  FROM
    system.system_credential_challenge c

  WHERE
    c.token_hash = p_token_hash

  LIMIT 1

  FOR UPDATE;


  IF NOT FOUND THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID'
    );

  END IF;


  IF
    v_challenge.consumed_at IS NOT NULL
    OR v_challenge.revoked_at IS NOT NULL
    OR v_challenge.expires_at <= CURRENT_TIMESTAMP
    OR v_challenge.attempt_count >=
       v_challenge.max_attempts
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID'
    );

  END IF;


  SELECT
    u.*

  INTO
    v_user

  FROM
    system.system_user u

  WHERE
    u.id =
      v_challenge.user_id
    AND u.archived_at IS NULL

  LIMIT 1

  FOR UPDATE;


  IF NOT FOUND
     OR v_user.status IN (
       'SUSPENDED',
       'CLOSED'
     )
  THEN

    UPDATE
      system.system_credential_challenge

    SET
      revoked_at =
        COALESCE(
          revoked_at,
          CURRENT_TIMESTAMP
        )

    WHERE
      id = v_challenge.id;


    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID'
    );

  END IF;


  -- Prevent reuse of current credential.

  IF system._auth_password_matches(
       p_new_password,
       v_user.password_hash
     )
  THEN

    UPDATE
      system.system_credential_challenge

    SET
      attempt_count =
        attempt_count + 1

    WHERE
      id = v_challenge.id;


    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'PASSWORD_REUSED'
    );

  END IF;


  -- Prevent reuse of any captured password-history credential.

  IF EXISTS (

    SELECT 1

    FROM
      system.system_password_history h

    WHERE
      h.user_id = v_user.id

      AND system._auth_password_matches(
        p_new_password,
        h.password_hash
      )

  ) THEN

    UPDATE
      system.system_credential_challenge

    SET
      attempt_count =
        attempt_count + 1

    WHERE
      id = v_challenge.id;


    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'PASSWORD_REUSED'
    );

  END IF;


  -- Preserve the credential being replaced.

  INSERT INTO
    system.system_password_history
  (
    id,
    user_id,
    password_hash,
    created_at
  )
  VALUES
  (
    gen_random_uuid()::text,
    v_user.id,
    v_user.password_hash,
    CURRENT_TIMESTAMP
  );


  -- Establish the new credential.

  UPDATE
    system.system_user

  SET
    password_hash =
      p_new_password_hash,

    is_active = true,
    is_verified = true,

    must_reset_password = false,

    failed_login_count = 0,
    locked_until = NULL,

    status =
      CASE

        WHEN status IN (
          'INVITED',
          'PENDING_VERIFICATION',
          'LOCKED'
        )
        THEN 'ACTIVE'

        ELSE status

      END,

    row_version =
      row_version + 1,

    updated_at =
      CURRENT_TIMESTAMP

  WHERE
    id = v_user.id;


  -- Credential establishment invalidates every existing session.

  UPDATE
    system.system_session

  SET
    is_active = false,

    invalidated_at =
      COALESCE(
        invalidated_at,
        CURRENT_TIMESTAMP
      ),

    last_activity_at =
      CURRENT_TIMESTAMP

  WHERE
    user_id = v_user.id
    AND is_active = true;


  -- Consume this challenge.

  UPDATE
    system.system_credential_challenge

  SET
    consumed_at =
      CURRENT_TIMESTAMP

  WHERE
    id = v_challenge.id;


  -- Revoke any other challenge for this identity.

  UPDATE
    system.system_credential_challenge

  SET
    revoked_at =
      CURRENT_TIMESTAMP

  WHERE
    user_id = v_user.id

    AND id <>
      v_challenge.id

    AND consumed_at IS NULL
    AND revoked_at IS NULL;


  -- Security evidence.

  INSERT INTO
    system.system_audit_event
  (
    id,
    user_id,
    school_id,
    action,
    entity_type,
    entity_id,
    before_state,
    after_state,
    created_at
  )
  VALUES
  (
    gen_random_uuid()::text,
    v_user.id,
    v_challenge.school_id,
    'CREDENTIAL_ESTABLISHED',
    'system_user',
    v_user.id,
    NULL,
    jsonb_build_object(
      'purpose',
      v_challenge.purpose
    )::text,
    CURRENT_TIMESTAMP
  );


  RETURN jsonb_build_object(
    'ok',
    true
  );

END
$function$;


REVOKE ALL
ON FUNCTION
