-- --------------------------------------------------------------------------
-- 6. Trusted own-password change.
--
-- The application never receives stored password-history hashes.
--
-- A valid HMAC-backed authenticated session is required through ctx_user_id()
-- and ctx_school_id().
--
-- Successful password change:
--   - verifies the existing password
--   - applies tenant password policy with a 12-character security floor
--   - rejects current/history reuse
--   - archives the replaced credential hash
--   - changes the password
--   - clears authentication lock state
--   - invalidates ALL existing sessions
--   - records security evidence
-- --------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION
  system.auth_change_own_password(
    p_current_password text,
    p_new_password text,
    p_new_password_hash text
  )
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path =
  pg_catalog,
  system,
  sukuux
AS $function$

DECLARE

  v_user_id text;
  v_school_id text;

  v_user
    system.system_user%ROWTYPE;

  v_min_length integer := 12;

  v_require_uppercase boolean := true;
  v_require_lowercase boolean := true;
  v_require_numbers boolean := true;
  v_require_symbols boolean := true;

BEGIN

  v_user_id :=
    system.ctx_user_id();

  v_school_id :=
    system.ctx_school_id();


  IF
    v_user_id IS NULL
    OR v_school_id IS NULL
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID_SESSION'
    );

  END IF;


  SELECT
    u.*

  INTO
    v_user

  FROM
    system.system_user u

  WHERE
    u.id = v_user_id
    AND u.archived_at IS NULL

  LIMIT 1

  FOR UPDATE;


  IF NOT FOUND THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'INVALID_SESSION'
    );

  END IF;


  IF
    v_user.is_active IS NOT TRUE
    OR v_user.status IN (
      'SUSPENDED',
      'CLOSED',
      'LOCKED'
    )
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'ACCOUNT_BLOCKED'
    );

  END IF;


  IF NOT system._auth_password_matches(
    p_current_password,
    v_user.password_hash
  ) THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'CURRENT_PASSWORD_INVALID'
    );

  END IF;


  SELECT

    COALESCE(
      (
        SELECT
          GREATEST(
            p.min_length,
            12
          )

        FROM
          system.system_password_policy p

        WHERE
          p.school_id = v_school_id

        LIMIT 1
      ),
      12
    ),

    COALESCE(
      (
        SELECT
          p.require_uppercase

        FROM
          system.system_password_policy p

        WHERE
          p.school_id = v_school_id

        LIMIT 1
      ),
      true
    ),

    COALESCE(
      (
        SELECT
          p.require_lowercase

        FROM
          system.system_password_policy p

        WHERE
          p.school_id = v_school_id

        LIMIT 1
      ),
      true
    ),

    COALESCE(
      (
        SELECT
          p.require_numbers

        FROM
          system.system_password_policy p

        WHERE
          p.school_id = v_school_id

        LIMIT 1
      ),
      true
    ),

    COALESCE(
      (
        SELECT
          p.require_symbols

        FROM
          system.system_password_policy p

        WHERE
          p.school_id = v_school_id

        LIMIT 1
      ),
      true
    )

  INTO
    v_min_length,
    v_require_uppercase,
    v_require_lowercase,
    v_require_numbers,
    v_require_symbols;


  IF
    p_new_password IS NULL
    OR length(p_new_password) <
       v_min_length
    OR (
      v_require_uppercase
      AND p_new_password !~ '[A-Z]'
    )
    OR (
      v_require_lowercase
      AND p_new_password !~ '[a-z]'
    )
    OR (
      v_require_numbers
      AND p_new_password !~ '[0-9]'
    )
    OR (
      v_require_symbols
      AND p_new_password !~ '[^A-Za-z0-9]'
    )
  THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'WEAK_PASSWORD'
    );

  END IF;


  IF system._auth_password_matches(
    p_new_password,
    v_user.password_hash
  ) THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'PASSWORD_REUSED'
    );

  END IF;


  IF EXISTS (

    SELECT 1

    FROM
      system.system_password_history h

    WHERE
      h.user_id =
        v_user.id

      AND system._auth_password_matches(
        p_new_password,
        h.password_hash
      )

  ) THEN

    RETURN jsonb_build_object(
      'ok',
      false,
      'reason',
      'PASSWORD_REUSED'
    );

  END IF;


  INSERT INTO
    system.system_password_history
  (
    id,
    user_id,
    password_hash,
    created_at
  )
  VALUES
  (
    gen_random_uuid()::text,
    v_user.id,
    v_user.password_hash,
    CURRENT_TIMESTAMP
  );


  UPDATE
    system.system_user

  SET
    password_hash =
      p_new_password_hash,

    must_reset_password =
      false,

    failed_login_count =
      0,

    locked_until =
      NULL,

    row_version =
      row_version + 1,

    updated_at =
      CURRENT_TIMESTAMP

  WHERE
    id = v_user.id;


  UPDATE
    system.system_session

  SET
    is_active =
      false,

    invalidated_at =
      COALESCE(
        invalidated_at,
        CURRENT_TIMESTAMP
      ),

    last_activity_at =
      CURRENT_TIMESTAMP

  WHERE
    user_id = v_user.id
    AND is_active = true;


  INSERT INTO
    system.system_audit_event
  (
    id,
    user_id,
    school_id,
    action,
    entity_type,
    entity_id,
    before_state,
    after_state,
    created_at
  )
  VALUES
  (
    gen_random_uuid()::text,
    v_user.id,
    v_school_id,
    'PASSWORD_CHANGED',
    'system_user',
    v_user.id,
    NULL,
    jsonb_build_object(
      'allSessionsRevoked',
      true
    )::text,
    CURRENT_TIMESTAMP
  );


  RETURN jsonb_build_object(
    'ok',
    true
  );

END
$function$;


